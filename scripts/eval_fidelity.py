    # StratifiedKFold to preserve class distribution in  each fold
    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=seed_val)

    # Lower is better for fidelity (closer to 0 means calssifiers are confused)
    f1_score = cross_val_score(classifier, X, Y, cv=cv, scoring='f1').mean()
    # accuracy_score = cross_val_score(classifier, X, Y, cv=cv, scoring='accuracy').mean()
    # real diversions (class 1) are few compared to synthetic ones (class 0), thus we use balanced accuracy
    balanced_accuracy = cross_val_score(classifier, X, Y, cv=cv, scoring=make_scorer(balanced_accuracy_score)).mean()

    # Numerical evaluation of fidelity
    print(f"{color.BOLD}Discriminative scores (lower is better):{color.END}")
    print(f"   F1: {f1_score:.3f}")
    # print(f"   Accuracy: {accuracy_score:.3f}")
    print(f"   Balanced Accuracy: {balanced_accuracy:.3f}")
    # print(f"   {color.BOLD}{color.BLUE}Overall fidelity: {np.mean([f1_score, accuracy_score])*100:.2f}%{color.END}")
    print(f"   {color.BOLD}{color.BLUE}Overall fidelity: {np.mean([f1_score, balanced_accuracy])*100:.2f}%{color.END}")

    # Store results
    results.append({
        "Model": model_name,
        "F1": f1_score,
        # "Accuracy": accuracy_score,
        "Balanced Accuracy": balanced_accuracy,
        "Overall Fidelity": np.mean([f1_score, balanced_accuracy])
    })

    # Classification report + confusion matrix (single train/test split) 
    X_train, X_test, Y_train, Y_test = train_test_split(
        X, Y, test_size=0.3, stratify=Y, random_state=seed_val
    )

    classifier.fit(X_train, Y_train)
    Y_pred = classifier.predict(X_test)

    print("-"*75)
    print(f"{color.BOLD}Classification Report (test size = 0.3):{color.END}")
    print(classification_report(Y_test, Y_pred, digits=4))

    # Plot confusion matrix
    print("-"*75)
    print(f"{color.BOLD}Confusion Matrix (test size = 0.3):{color.END}")
    cm = confusion_matrix(Y_test, Y_pred)
    print(cm)
    sns.heatmap(
        cm, annot=True, fmt="d", cmap="Blues",
        linewidths=2, linecolor='black', cbar=False
    )
    plt.title(f"Confusion Matrix: real vs synthetic generated by \"{model_name}\"")
    plt.xlabel("Predicted")
    plt.ylabel("Actual")
    plt.tight_layout()
    plt.show()

